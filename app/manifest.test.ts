import { describe, expect, it } from "vitest";

import { generateStaticParams, GET } from "./icons/[name]/route";
import manifest from "./manifest";

describe("web app manifest (Add to Home Screen)", () => {
  const appManifest = manifest();
  it("has what a browser needs to offer installation", () => {
    expect(appManifest.name).toBeTruthy();
    expect(appManifest.short_name).toBe("AirWise");
    expect(appManifest.start_url).toBe("/");
    expect(appManifest.display).toBe("standalone");
    expect(appManifest.theme_color).toMatch(/^#[0-9a-f]{6}$/i);
    expect(appManifest.background_color).toMatch(/^#[0-9a-f]{6}$/i);
  });
  it("lists 192 and 512 icons plus a maskable one", () => {
    const sizes = (appManifest.icons ?? []).map((i) => `${i.sizes}:${i.purpose}`);
    expect(sizes).toEqual(
      expect.arrayContaining(["192x192:any", "512x512:any", "512x512:maskable"]),
    );
    for (const i of appManifest.icons ?? []) expect(i.type).toBe("image/png");
  });
  it("every icon path is generated by the icon route", () => {
    const names = generateStaticParams().map((p) => p.name);
    for (const i of appManifest.icons ?? []) expect(names).toContain(i.src.replace("/icons/", ""));
  });
});

describe("icon route", () => {
  const call = (name: string) =>
    GET(new Request(`http://x/icons/${name}`), { params: Promise.resolve({ name }) });
  it("returns a PNG for each icon, and 404 for anything else", async () => {
    for (const name of ["192", "512", "maskable"]) {
      const res = await call(name);
      expect(res.status).toBe(200);
      expect(res.headers.get("content-type")).toMatch(/image\/png/);
      const bytes = new Uint8Array(await res.arrayBuffer());
      expect([...bytes.slice(0, 4)]).toEqual([0x89, 0x50, 0x4e, 0x47]); // PNG signature
    }
    expect((await call("../../etc/passwd")).status).toBe(404);
    expect((await call("9999")).status).toBe(404);
  });
});
